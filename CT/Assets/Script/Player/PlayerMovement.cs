using UnityEngine;
using UnityEngine.InputSystem;

/// <summary>
/// プレイヤー共通の移動処理クラス
/// </summary>
public class PlayerMovement : CharacterMovement
{
    //=====================================================================
    // 変数
    //=====================================================================

    [Header("操作設定")]

    [SerializeField] 
    private bool canControl = false;

    //=====================================================================
    // プロパティ
    //=====================================================================

    public bool CanControl => canControl;

    //=====================================================================
    // 関数
    //=====================================================================

    /// <summary>
    /// 操作可能状態を変更する
    /// </summary>
    public void SetControlEnabled(bool enabled)
    {
        canControl = enabled;
    }
}
