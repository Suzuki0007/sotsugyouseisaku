/// <summary>
/// 立ち絵の表情の種類（全キャラクター共通）
/// </summary>
///
/// 表情を増やすときは、ここに1行追加する。
/// ※ 途中に追加すると、既存の会話データの選択がずれるので、必ず末尾に追加すること
public enum Expression
{
    Normal,     // 通常
    Smile,      // 笑顔
    Angry,      // 怒り
    Sad,        // 悲しみ
    Surprise,   // 驚き
    Troubled,   // 困り
}
